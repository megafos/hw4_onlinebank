"""Reproducible design estimates."""
import json
import pprint
from pathlib import Path

def calculate(users=3_000_000):
    rates = {'transactional': 2, 'service': 3, 'marketing_inbound': 5}
    daily = {k: users*v for k,v in rates.items()}
    total = sum(daily.values())
    critical = daily['transactional']
    attempts = 1 + .10 + .02
    return {
        'daily': daily, 'total_daily': total,
        'average_per_second': {k: v/86400 for k,v in daily.items()},
        'total_average_per_second': total/86400,
        'critical_attempts_daily_base': critical*attempts,
        'critical_write_operations_daily_base': critical*(2+4*attempts),
        'input_kafka_gb_7d_rf3_headroom50': total*1000*7*3*1.5/1e9,
        'critical_raw_history_gb_30d': critical*30*(1000+attempts*500)/1e9,
        'critical_history_tb_index2_copies3': critical*30*(1000+attempts*500)*2*3/1e12,
        'audit_gb_365d': critical*365*300/1e9,
        'sms_daily_base': critical*.10, 'email_daily_base': critical*.02,
        'illustrative_external_cost_daily': critical*.10*2+critical*.02*.01,
        'sms_cost_full_push_outage_daily': critical*2,
    }

def main():
    result = {
        'units': 'Decimal GB/TB; illustrative costs, not vendor quotes',
        'dau_case': calculate(), 'mau_sensitivity': calculate(10_000_000),
        'peak': {'critical':5000, 'service':2500, 'marketing':1000,
                 'total':8500, 'qualification_total':17000,
                 'critical_base_attempts':5600,
                 'critical_max_fast_requests':25000,
                 'qualification_max_fast_requests':50000,
                 'critical_max_outgoing_http_with_lookup':75000,
                 'qualification_max_outgoing_http_with_lookup':150000,
                 'critical_base_write_operations':32400,
                 'critical_stress_write_operations':110000,
                 'qualification_stress_write_operations_per_shard':27500},
        'campaign_per_second_20min': 1_000_000/1200,
        'inflight_at_5000_per_second_and_60s':300000,
        'hour_outage_backlog_at_peak':18_000_000,
        'availability_budget_minutes_30d':30*24*60*.0005,
        'slo60_error_budget_daily_at_6m_eligible':3000,
        'slo24h_error_budget_daily_at_6m_eligible':600,
    }
    target=Path(__file__).resolve().parent/'capacity_planning_output.py'
    target.write_text('# Generated by capacity_planning.py; data only.\nRESULTS = '+pprint.pformat(result, sort_dicts=False)+'\n', encoding='utf-8')
    print(json.dumps(result, ensure_ascii=False, indent=2))
if __name__=='__main__': main()
